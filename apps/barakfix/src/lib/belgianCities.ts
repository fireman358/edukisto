// Liste triee par code postal (ordre numerique) pour l'affichage
export const BELGIAN_CITIES_BY_CODE: BelgianCity[] = [...BELGIAN_CITIES].sort(
  (a, b) => a.code.localeCompare(b.code)
);

export function findCityByCode(code: string): BelgianCity | undefined {
  return BELGIAN_CITIES.find((c) => c.code === code);
}

export function findCityByName(name: string): BelgianCity | undefined {
  const n = name.trim().toLowerCase();
  return BELGIAN_CITIES.find((c) => c.name.toLowerCase() === n);
}
